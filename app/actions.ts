"use server";

import { GoogleGenAI } from "@google/genai";

const TEXT_MODEL = 'gemini-2.0-flash-exp';
const IMAGE_MODEL = 'gemini-2.5-flash-image';

const getAI = (userKey?: string) => {
    const key = userKey;
    if (!key) {
        throw new Error("API Key is missing. Please provide it in Settings.");
    }
    return new GoogleGenAI({ apiKey: key });
};

export const checkConfigurationAction = async (apiKey?: string): Promise<{ status: 'ok' | 'error', message: string }> => {
    try {
        const ai = getAI(apiKey);
        // Simple test call
        await ai.models.generateContent({
            model: TEXT_MODEL,
            contents: [{ role: 'user', parts: [{ text: 'Test' }] }],
        });
        return { status: 'ok', message: "Google GenAI is configured and working." };
    } catch (error) {
        return { status: 'error', message: `API Connection Failed: ${error instanceof Error ? error.message : String(error)}` };
    }
};

const fileToGenerativePart = async (file: File) => {
  const arrayBuffer = await file.arrayBuffer();
  const base64 = Buffer.from(arrayBuffer).toString('base64');
  return {
    inlineData: { data: base64, mimeType: file.type },
  };
};

const extractInlineImage = (response: any): string => {
    const imagePart = response.candidates?.[0]?.content?.parts?.find((p: any) => p.inlineData?.data);
    
    if (!imagePart?.inlineData?.data) {
        throw new Error("No image generated by Gemini.");
    }
    
    return imagePart.inlineData.data;
};



export const enhancePromptAction = async (prompt: string, apiKey?: string): Promise<string> => {
    const systemInstruction = `You are an expert creative director specializing in visual content. Your task is to enhance the following user prompt to generate a more detailed and visually rich image. Do not generate the image description itself, but rather a better prompt for an AI image generator.

Rules:
- Add specific details about style, mood, and composition.
- Include technical photography or art terms where relevant (e.g., 'shot on 35mm film', 'depth of field', 'chiaroscuro lighting').
- Specify lighting, colors, and atmosphere.
- Make the description more vivid and detailed.
- Keep the core subject of the original prompt.
- The output must be only the enhanced prompt, with no additional text, titles, or explanations.`;

    const ai = getAI(apiKey);
    const response = await ai.models.generateContent({
        model: TEXT_MODEL,
        contents: [{ role: 'user', parts: [{ text: `Original Prompt: "${prompt}"` }] }],
        config: {
            systemInstruction,
            temperature: 0.8,
        },
    });

    const text = response.candidates?.[0]?.content?.parts?.[0]?.text;
    return text?.trim() || "";
};

export const stageRealEstateImageAction = async (formData: FormData): Promise<string> => {
    const imageFile = formData.get('image') as File;
    const style = formData.get('style') as string;
    const apiKey = formData.get('apiKey') as string | undefined;

    if (!imageFile || !style) throw new Error("Missing image or style");

    const imagePart = await fileToGenerativePart(imageFile);
    
    const prompt = `Virtually stage this empty or outdated room in a "${style}" style. Photorealistic. Keep the structural elements (walls, windows, doors) exactly the same, only add furniture and decor.`;
    
    try {
        const ai = getAI(apiKey);
        const response = await ai.models.generateContent({
            model: IMAGE_MODEL,
            contents: [
                { role: 'user', parts: [imagePart, { text: prompt }] }
            ],
            config: {
                responseModalities: ['IMAGE'],
            }
        });

        return extractInlineImage(response);
    } catch (e) {
        console.error("Gemini generation failed:", e);
        throw new Error(`Failed to generate image with Gemini: ${e instanceof Error ? e.message : String(e)}`);
    }
};

