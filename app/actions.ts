export const generateBeautyAdImageExperimentalAction = async (formData: FormData): Promise<{ image: string; headline: string; tagline: string }> => {
    const imageFile = formData.get('image') as File;
    const prompt = formData.get('prompt') as string;
    const style = formData.get('style') as string;
    const adText = formData.get('adText') as string;
    const apiKey = formData.get('apiKey') as string | undefined;

    if (!imageFile || !prompt || !style) throw new Error("Missing image, prompt or style");

    // 1. Analyze image and generate copy (Headline/Tagline) only
    const imagePart = await fileToGenerativePart(imageFile);
    
    const analysisPrompt = `
    Analyze this product image and the user's request.
    User Request: Place this product in a "${style}" scene. Context: ${prompt}.
    ${adText ? `Requirement: The image MUST include the text "${adText}" visible in the scene.` : ''}

    Tasks:
    1. Write a catchy, production-level ad headline (max 10 words).
    2. Write a short, persuasive tagline (max 15 words).

    Return ONLY a JSON object with this structure:
    {
        "headline": "string",
        "tagline": "string"
    }
    `;

    const ai = getAI(apiKey);
    const result = await ai.models.generateContent({
        model: TEXT_MODEL,
        contents: [
            { role: 'user', parts: [imagePart, { text: analysisPrompt }] }
        ]
    });

    const responseText = result.candidates?.[0]?.content?.parts?.[0]?.text || "{}";
    const cleanJson = responseText.replace(/```json|```/g, '').trim();
    let parsedData;
    
    try {
        parsedData = JSON.parse(cleanJson);
    } catch (e) {
        console.error("Failed to parse Gemini response:", responseText);
        // Fallback
        parsedData = {
            headline: "Experience Beauty",
            tagline: "Radiance redefined."
        };
    }

    // 2. Generate Image using Gemini 2.5 Flash (Nano Banana) with New Workflow
    if (!AD_STYLE_PROMPTS[style]) {
        console.warn(`Unknown ad style "${style}", falling back to Bold Modern`);
    }
    const stylePrompt = AD_STYLE_PROMPTS[style] || AD_STYLE_PROMPTS['Bold Modern'];
    
    const imageGenerationPrompt = `
    ${BASE_AD_PROMPT}

    ---
    INPUT CONTEXT:
    User Request: "${prompt}"
    Specific Text to Include: "${adText || `${parsedData.headline} - ${parsedData.tagline}`}"
    
    ---
    STYLE DEFINITION:
    ${stylePrompt}
    
    ---
    INSTRUCTIONS:
    Combine the INPUT CONTEXT with the STYLE DEFINITION to generate the final image.
    CRITICAL: The text MUST be rendered as a physical object in the scene (e.g. a neon sign, a poster on the wall, or 3D letters standing on the floor). It must be BEHIND the product. Do not overlay text digitally.
    Place the text strictly BEHIND the product, never overlapping.
    `;

    try {
        const response = await ai.models.generateContent({
            model: IMAGE_MODEL,
            contents: [
                { role: 'user', parts: [imagePart, { text: imageGenerationPrompt }] }
            ],
            config: {
                responseModalities: ['IMAGE'],
            }
        });

        const imageData = extractInlineImage(response);
        return {
            image: imageData,
            headline: parsedData.headline,
            tagline: parsedData.tagline
        };
    } catch (e) {
        console.error("Gemini generation failed:", e);
        throw new Error(`Failed to generate image with Gemini: ${e instanceof Error ? e.message : String(e)}`);
    }
};